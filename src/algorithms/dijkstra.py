import heapq
import math

def dijkstra(graph, start_node):
    """
    Implements Dijkstra's algorithm to find the shortest paths from a start_node
    to all other nodes in a weighted graph.

    Args:
        graph (dict): A dictionary representing the graph where keys are nodes
                      and values are dictionaries of neighboring nodes and their
                      edge weights.
                      Example: {'A': {'B': 1, 'C': 4}, 'B': {'A': 1, 'D': 2}, ...}
        start_node: The node from which to start the algorithm.

    Returns:
        tuple: A tuple containing two dictionaries:
               - distances (dict): Shortest distance from start_node to each other node.
               - predecessors (dict): Predecessor of each node in the shortest path.
                                     Can be used to reconstruct the path.
    """
    if start_node not in graph:
        raise ValueError(f"Start node '{start_node}' not found in the graph.")

    # Initialize distances with infinity for all nodes and 0 for the start_node
    distances = {node: math.inf for node in graph}
    distances[start_node] = 0

    # Priority queue to store (distance, node).
    # It will always extract the node with the smallest distance.
    priority_queue = [(0, start_node)]

    # Dictionary to store the path taken to reach a node
    predecessors = {node: None for node in graph}

    while priority_queue:
        current_distance, current_node = heapq.heappop(priority_queue)

        # If we have already found a shorter path to this node, skip
        if current_distance > distances[current_node]:
            continue

        # Explore neighbors
        for neighbor, weight in graph[current_node].items():
            distance = current_distance + weight

            # If a shorter path to the neighbor is found
            if distance < distances[neighbor]:
                distances[neighbor] = distance
                predecessors[neighbor] = current_node
                heapq.heappush(priority_queue, (distance, neighbor))

    return distances, predecessors

def reconstruct_path(predecessors, start_node, end_node):
    """
    Reconstructs the shortest path from the start_node to the end_node
    using the predecessors dictionary generated by Dijkstra's algorithm.

    Args:
        predecessors (dict): Dictionary mapping each node to its predecessor
                             in the shortest path from the start_node.
        start_node: The starting node of the overall path.
        end_node: The target node for which to reconstruct the path.

    Returns:
        list: A list of nodes representing the shortest path from start_node
              to end_node. Returns an empty list if no path exists.
    """
    path = []
    if end_node not in predecessors or (predecessors[end_node] is None and end_node != start_node):
        return [] # No path exists

    current = end_node
    while current is not None:
        path.append(current)
        current = predecessors[current]
        if current == start_node:
            path.append(start_node)
            break

    return path[::-1] # Reverse the path to get it from start to end

