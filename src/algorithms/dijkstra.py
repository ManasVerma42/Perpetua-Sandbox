    # Example Usage:
    graph = {
        'A': {'B': 1, 'C': 4},
        'B': {'A': 1, 'D': 2, 'E': 7},
        'C': {'A': 4, 'F': 5},
        'D': {'B': 2, 'E': 3},
        'E': {'B': 7, 'D': 3, 'F': 6},
        'F': {'C': 5, 'E': 6}
    }

    start_node = 'A'
    distances, predecessors = dijkstra(graph, start_node)

    print(f"Shortest distances from node '{start_node}':")
    for node, dist in distances.items():
        if dist == math.inf:
            print(f"  {node}: No path")
        else:
            print(f"  {node}: {dist}")

    print("\nPredecessors for shortest paths:")
    for node, pred in predecessors.items():
        print(f"  {node}: {pred}")

    print("\nReconstructing paths:")
    end_node_path = 'F'
    path_to_F = reconstruct_path(predecessors, start_node, end_node_path)
    if path_to_F:
        print(f"  Path from {start_node} to {end_node_path}: {' -> '.join(path_to_F)}")
    else:
        print(f"  No path found from {start_node} to {end_node_path}.")

    end_node_path = 'E'
    path_to_E = reconstruct_path(predecessors, start_node, end_node_path)
    if path_to_E:
        print(f"  Path from {start_node} to {end_node_path}: {' -> '.join(path_to_E)}")
    else:
        print(f"  No path found from {start_node} to {end_node_path}.")

    # Example with a disconnected graph or non-existent start node
    graph_disconnected = {
        'X': {'Y': 1},
        'Y': {'X': 1},
        'Z': {'W': 1},
        'W': {'Z': 1}
    }
    start_node_dis = 'X'
    distances_dis, _ = dijkstra(graph_disconnected, start_node_dis)
    print(f"\nShortest distances from node '{start_node_dis}' in disconnected graph:")
    for node, dist in distances_dis.items():
        if dist == math.inf:
            print(f"  {node}: No path")
        else:
            print(f"  {node}: {dist}")

